test('snapshot research tools compare real runs and retrieve English cited findings',async({page})=>{
 await page.goto('/present');
 await page.getByLabel('Data availability',{exact:true}).selectOption('runs');
 await expect(page.getByText('4 matching records · 0 / 4 selected',{exact:true})).toBeVisible();
 await page.getByRole('checkbox',{name:'Compare CFI-G',exact:true}).check();
 await page.getByRole('checkbox',{name:'Compare Saffire-II',exact:true}).check();
 await page.getByRole('button',{name:'Compare selected',exact:true}).click();
 const comparison=page.getByRole('region',{name:'Selected investigation comparison'});
 await expect(comparison.getByRole('table')).toHaveCount(3);
 await expect(comparison.getByRole('cell').filter({hasText:'burn duration: 900 s'})).toBeVisible();
 await expect(comparison.getByText('Different quantities, units or measurement methods are present.',{exact:false})).toBeVisible();
 const exportPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export comparison JSON ↓'}).click();
 const {readFile}=await import('node:fs/promises');
 const bundle=JSON.parse(await readFile((await (await exportPromise).path())!,'utf8'));
 expect(bundle.investigations).toHaveLength(2);
 const saffire=bundle.investigations.find((s:{acronym:string})=>s.acronym==='Saffire-II');
 expect(saffire.runs.find((r:{id:string})=>r.id==='2-9').material).toBeNull();
 expect(saffire.runs[0].measurements).toEqual([]);
 await page.getByRole('button',{name:'Evidence search',exact:true}).click();
 await page.getByLabel('Research question',{exact:true}).fill('heat-release oxygen consumption');
 await page.getByRole('button',{name:'Retrieve evidence',exact:true}).click();
 await expect(page.getByText('Evidence ID: nasa-bass-report-f1',{exact:false})).toBeVisible();
 await expect(page.getByText('substantially below 100 W',{exact:false})).toBeVisible();
 await page.getByLabel('Research question',{exact:true}).fill('PSI-181');
 await page.getByRole('button',{name:'Retrieve evidence',exact:true}).click();
 await expect(page.getByText('Insufficient evidence in the current dataset.',{exact:false})).toBeVisible();
});

test('observation CSV preserves qualitative results, nulls and source locators',async({page})=>{
 await page.goto('/present');
 const promise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export observation CSV ↓',exact:true}).click();
 const download=await promise;expect(download.suggestedFilename()).toBe('flameatlas-saffire-ii-observations.csv');
 const {readFile}=await import('node:fs/promises');
 const csv=await readFile((await download.path())!,'utf8');
 expect(csv.split('\r\n').filter(Boolean)).toHaveLength(10);
 expect(csv.match(/Insignificant/g)).toHaveLength(4);
 expect(csv).toContain('PSI-99 Version 5; Experimental Table; Sample 2-9');
 expect(csv).toContain('"burn duration","900","s","900 s"');
});

test('standalone scenario evaluation exposes bounds and exports provenance',async({page})=>{
 await page.goto('/present');
 await page.getByRole('button',{name:'Scenario explorer',exact:true}).click();
 await page.getByLabel('Scenario gravity',{exact:true}).selectOption('lunar');
 await page.getByRole('button',{name:'Evaluate scenario',exact:true}).click();
 await expect(page.getByText('pO₂ = 21.278 kPa',{exact:false})).toBeVisible();
 await expect(page.getByText('Outside available evidence coverage',{exact:false})).toHaveCount(10);
 const promise=page.waitForEvent('download');await page.getByRole('button',{name:'Export scenario JSON ↓'}).click();
 const {readFile}=await import('node:fs/promises');
 const exported=JSON.parse(await readFile((await (await promise).path())!,'utf8'));
 expect(exported.scenario.gravity).toBe('lunar');expect(exported.ranking).toHaveLength(10);
 expect(exported.methodology_version).toBe('conservative-run-match-v1');
 expect(exported.ranking.every((r:{outside_coverage:boolean})=>r.outside_coverage)).toBeTruthy();
 expect(exported.ranking.find((r:{investigation:{acronym:string}})=>r.investigation.acronym==='SAME').components.gravity).toBeNull();
 expect(exported.ranking.find((r:{investigation:{acronym:string}})=>r.investigation.acronym==='Saffire-II').components.gravity).toBe(0);
});
